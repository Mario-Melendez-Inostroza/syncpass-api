-- V2: dominio SyncPass (caso DSY1105 §3.2): proyectos, eventos, asistentes, asistencias y encuestas.
--
-- Derivado del DDL que genera Hibernate para las entidades (build/schema.sql). Si se cambia una entidad,
-- hay que añadir una migración nueva; NO editar esta una vez aplicada en una base real.
--
-- Sin datos personales: asistentes solo guarda un código sintético y el tipo de participante (caso §5.1).

create table proyectos (
    id             bigint generated by default as identity,
    titulo         varchar(150)  not null,
    descripcion    varchar(1000),
    area_tematica  varchar(80)   not null,
    unidad_vecinal varchar(120)  not null,
    fecha_inicio   date          not null,
    fecha_termino  date,
    estado         varchar(20)   not null
        check (estado in ('PLANIFICADO', 'EN_CURSO', 'CERRADO')),
    actualizado_en timestamp(6) with time zone not null,
    primary key (id)
);

create table eventos (
    id                    bigint generated by default as identity,
    proyecto_id           bigint       not null,
    nombre                varchar(150) not null,
    fecha_hora_programada timestamp(6) with time zone not null,
    cupos_maximos         integer,
    recinto               varchar(200),
    latitud               float(53),
    longitud              float(53),
    radio_metros          integer      not null,
    actualizado_en        timestamp(6) with time zone not null,
    primary key (id),
    constraint fk_eventos_proyecto foreign key (proyecto_id) references proyectos (id)
);

create table asistentes (
    id                 bigint generated by default as identity,
    codigo             varchar(40) not null,
    tipo               varchar(20) not null
        check (tipo in ('ESTUDIANTE', 'VECINO', 'DOCENTE')),
    estado_inscripcion varchar(20) not null
        check (estado_inscripcion in ('INSCRITO', 'SIN_INSCRIPCION')),
    actualizado_en     timestamp(6) with time zone not null,
    primary key (id),
    constraint uk_asistentes_codigo unique (codigo)
);

create table asistencias (
    id                 bigint generated by default as identity,
    uuid               varchar(36) not null,
    evento_id          bigint      not null,
    asistente_id       bigint      not null,
    marcado_en         timestamp(6) with time zone not null,
    latitud            float(53),
    longitud           float(53),
    distancia_metros   integer,
    estado_validacion  varchar(20) not null
        check (estado_validacion in ('VALIDA', 'FUERA_DE_RADIO', 'SIN_UBICACION')),
    registrado_por_sub varchar(64) not null,
    recibido_en        timestamp(6) with time zone not null,
    primary key (id),
    -- uuid: idempotencia (lo genera el teléfono; reenviar un lote no duplica filas).
    constraint uk_asistencias_uuid unique (uuid),
    -- una marcación por asistente y evento.
    constraint uk_asistencias_evento_asistente unique (evento_id, asistente_id),
    constraint fk_asistencias_evento foreign key (evento_id) references eventos (id),
    constraint fk_asistencias_asistente foreign key (asistente_id) references asistentes (id)
);

create table encuestas (
    id            bigint generated by default as identity,
    uuid          varchar(36) not null,
    asistencia_id bigint      not null,
    satisfaccion  integer     not null check (satisfaccion >= 1 and satisfaccion <= 5),
    utilidad      integer     not null check (utilidad >= 1 and utilidad <= 5),
    comentarios   varchar(1000),
    enviada_en    timestamp(6) with time zone not null,
    recibida_en   timestamp(6) with time zone not null,
    primary key (id),
    constraint uk_encuestas_uuid unique (uuid),
    -- una encuesta por asistencia.
    constraint uk_encuestas_asistencia unique (asistencia_id),
    constraint fk_encuestas_asistencia foreign key (asistencia_id) references asistencias (id)
);

-- Índices. Las claves únicas ya cubren las búsquedas por uuid y por (evento, asistente); el prefijo
-- evento_id de uk_asistencias_evento_asistente sirve también para contar las marcaciones de un evento.
create index ix_eventos_proyecto on eventos (proyecto_id);

-- GET /api/sync/catalogo?desde= recorre estas tres columnas.
create index ix_proyectos_actualizado_en  on proyectos  (actualizado_en);
create index ix_eventos_actualizado_en    on eventos    (actualizado_en);
create index ix_asistentes_actualizado_en on asistentes (actualizado_en);
