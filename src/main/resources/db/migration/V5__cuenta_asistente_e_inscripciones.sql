-- NO se copian correo ni nombre a esta base: el asistente sigue siendo un codigo sintetico y un tipo (caso §5.1).

alter table asistentes add column usuario_sub varchar(64);
alter table asistentes add constraint uk_asistentes_usuario_sub unique (usuario_sub);

create table inscripciones (
    id           bigint generated by default as identity primary key,
    asistente_id bigint      not null references asistentes (id) on delete cascade,
    evento_id    bigint      not null references eventos (id) on delete cascade,
    creada_en    timestamp(6) with time zone not null,
    constraint uk_inscripciones_asistente_evento unique (asistente_id, evento_id)
);

create index idx_inscripciones_evento on inscripciones (evento_id);
